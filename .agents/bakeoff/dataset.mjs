/** Sanity: cuenta por idioma/campo. Lanza si algo no cuadra. */
export function sanityDataset() {
  const by = (pred) => DATASET.filter(pred).length
  const checks = {
    total: DATASET.length === 120,
    es: by((d) => d.lang === 'es') === 60,
    en: by((d) => d.lang === 'en') === 60,
    ragLiteral: by((d) => d.action === 'rag' && d.searchMode === 'literal') === 32,
    summary: by((d) => d.isSummary) === 12,
    web: by((d) => d.needsWeb) === 12,
    pageRef: by((d) => d.isPageRef) === 16,
    direct: by((d) => d.action === 'direct') === 10,
    chart: by((d) => d.action === 'chart') === 12,
    agent: by((d) => d.action === 'agent') === 8,
    mcp: by((d) => d.action === 'mcp') === 8,
    uniqueIds: new Set(DATASET.map((d) => d.id)).size === 120,
    pageRefImpliesRag: DATASET.every((d) => !d.isPageRef || d.action === 'rag'),
    webImpliesWebSearch: DATASET.every((d) => d.needsWeb === (d.action === 'web_search')),
    summaryImpliesRag: DATASET.every((d) => !d.isSummary || d.action === 'rag'),
  }
  const failed = Object.entries(checks).filter(([, ok]) => !ok).map(([k]) => k)
  return { ok: failed.length === 0, failed, checks }
}
